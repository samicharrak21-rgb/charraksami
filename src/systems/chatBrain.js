  if (has(/^(هلا|هلو|مرحبا|مرحبتين|اهلين|اهلا|هاي|hi|hello|hey|يا هلا)/)) return R([`هلا والله بـ{n} ${timeGreeting()} {e}`, 'أهلين يا {n}، نورت الشات {e}', 'يا هلا ومرحبا {e} وش مسوي اليوم؟']);
  if (has(/(صباح الخير|صباحو|صباح النور)/)) return R(['صباح الورد يا {n} ☀️ قهوتك جاهزة؟', 'صباح النور والسرور {e} لا تنسى راتبك اليومي: اكتب «يومي»']);
  if (has(/(مساء الخير|مساء النور|مسا الخير)/)) return R(['مساء الفل يا {n} 🌙', 'مساء النور {e} وش أحلى شي صار معك اليوم؟']);
  if (has(/(تصبح علي خير|تصبحون علي خير|رايح انام|بنام|نعسان|good night)/)) return R(['وأنت من أهله يا {n} 😴 لا تنسى أذكار النوم: اكتب «اذكار النوم»', 'نوم العوافي {e} بكرة نكمل']);
  if (has(/(باي|مع السلامه|سلام عليكم ورحمه|اشوفكم|bye)/)) return R(['في أمان الله يا {n} 👋', 'الله معك، لا تطول علينا {e}']);

  // 4) أحوال ومشاعر
  if (has(/(كيفك|كيف حالك|شلونك|شخبارك|وش اخبارك|عامل ايه|كيف الحال|how are)/)) { mem.topic = 'حال'; return R(['بخير دامك بخير {e} وأنت شلونك؟', 'تمام الحمد لله، ومبسوط إنك سألت {e} وأنت؟', 'زي الفل يا {n} {e} طمني عنك']); }
  if (has(/^(بخير|تمام|الحمد لله|الحمدلله|زين|كويس|منيح|good|fine)/)) return R(['دوم يا رب {e}', 'الحمد لله، دايم يا {n} {e} وش ناوي تسوي اليوم؟', 'يارب دايماً 💙']);
  if (has(/(زعلان|حزين|متضايق|مكتئب|طفشان|ضايق|مقهور|تعبان نفسيا|sad)/)) { mem.mood = 'sad'; return R(ADVICE_SAD); }
  if (has(/(طفش|ملل|زهق|مليت|bored)/)) return R(['طفشان؟ يلا نكسر الملل {e} [game:fastest]', 'عندي الحل: لعبة جماعية الحين! [game:quiz]', 'جرب «كنز 500» أو «صاروخ 300» وخل الحظ يتكلم 🎲']);
  if (has(/(مبسوط|فرحان|سعيد|happy|ونااسه|وناسه)/)) return R(['الله يديم فرحتك يا {n} 🎉', 'يا سلام! وش السالفة؟ {e}']);
  if (has(/(تعبان|مرهق|جوعان|عطشان)/)) return R(['الله يعطيك العافية يا {n}، ارتاح شوي {e}', 'قم كل لك شي وتعال، ما نقدر نخسرك 😄']);

  if (has(/(خرب|خربت|انكسر|ضاع|ضاعت|مشكله|مصيبه|رسبت|خسرت|تعطل)/)) return R(['أفا! سلامتك يا {n} 😟 وش صار بالضبط؟', 'لا حول ولا قوة إلا بالله، الله يعوضك بأحسن منها يا {n} 💙', 'معليش يا {n}، كل مشكلة ولها حل {e} احكي لي']);
  if (has(/(نجحت|تخرجت|ربحت|فزت|توظفت|انقبلت|تزوجت)/)) return R(['مبرووووك يا {n}! 🎉🎉', 'ألف مبروك! تستاهل كل خير {e}', 'كفووو! هذا يبيله احتفال 🥳 [game:fastest]']);

  // 5) عن البوت
