const norm = (t) => String(t || '').replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
  .replace(/[\u064B-\u0652ـ]/g, '').replace(/(.)\1{2,}/g, '$1$1').toLowerCase().trim();

const recent = new Map();   // channelId -> [replies]
const users = new Map();    // userId -> { name, mood, topic, last, count }
const riddles = new Map();  // channelId -> { a, at }

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
function fresh(channelId, options) {
  const used = recent.get(channelId) || [];
  const pool = options.filter((o) => !used.includes(o));
  const r = pick(pool.length ? pool : options);
  used.push(r); while (used.length > 25) used.shift();
  recent.set(channelId, used);
  return r;
}

