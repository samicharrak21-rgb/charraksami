  const mem = users.get(ctx.userId) || { count: 0 };
  mem.count++; mem.last = Date.now(); users.set(ctx.userId, mem);
  const R = (arr) => fresh(ch, arr).replace(/\{n\}/g, n).replace(/\{e\}/g, e()).replace(/\{bot\}/g, bot);
  const has = (re) => re.test(t);

  // 0) جواب لغز مفتوح
  const rd = riddles.get(ch);
  if (rd && t && Date.now() - rd.at < 5 * 60000 && t.length < 30) {
    if (t.includes(rd.a) || rd.a.includes(t.replace(/^ال/, ''))) { riddles.delete(ch); return R([`صح عليك يا {n}! الجواب **${rd.a}** 🎉 [reward:${ctx.userId}:100]`, `كفو يا {n} 👏 الجواب **${rd.a}**! خذ هدية [reward:${ctx.userId}:100]`]); }
    if (has(/(استسلم|ما اعرف|الجواب|قول الحل|وش الحل)/)) { riddles.delete(ch); return `الجواب كان: **${rd.a}** ${e()} تبي لغز ثاني؟ قول «لغز»`; }
  }
  if (!t || t === '👋') return R([`هلا {n}! ${timeGreeting()} {e} وش أخبارك؟`, 'نادِيتني؟ أنا هنا {e}', 'لبيه {n} {e} آمرني']);

  // 1) حساب
  const c = calc(raw);
  if (c && (has(/(كم|احسب|يساوي|=|\?|؟)/) || /^[\d\s+\-*/×÷%.^]+$/.test(raw))) return `🧮 ${c.expr} = **${c.v.toLocaleString('en-US')}** ${e()}`;

  // 2) اختيار «X ولا Y» / «اختار»
