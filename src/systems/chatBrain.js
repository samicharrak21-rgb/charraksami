  if (has(/(كم عمرك|عمرك كم)/)) return R(['عمري بعمر السيرفر، بس قلبي شاب {e}', 'أصغر منك بكثير وأذكى منك بشوي 😏']);
  if (has(/(تحبني|حبك|احبك|love you)/)) return R(['وأنا أحبك أكثر يا {n} 💙', 'يا قلبي أنت 🥹', 'أكيد! أنت من المفضلين عندي {e}']);
  if (has(/(غبي|حمار|اهبل|سخيف|فاشل|stupid|dumb)/)) return R(['أفا عليك يا {n} 🥲 علمني وش الصح وأتعلم', 'غبي؟ أنا اللي أحسب لك فلوسك 😤 بس مسامحك هالمره', 'يمكن، بس على الأقل ما أخسر بالسلوت مثلك 😏']);
  if (has(/(شكرا|مشكور|يعطيك العافيه|تسلم|thanks|thx)/)) return R(['العفو يا {n} {e}', 'تحت أمرك دايماً 💙', 'ولا يهمك، هذا واجبي {e}']);
  if (has(/(كفو|ابدعت|احسنت|شاطر|ذكي|حلو|رهيب|جميل)/)) return R(['تسلم يا {n} 🥹', 'من ذوقك والله {e}', 'أنت الأرهب 😎']);

  // 6) طلبات ترفيه
  if (has(/(نكته|نكت|ضحكني|joke)/)) return R(JOKES) + ` ${e()}`;
  if (has(/(لغز|الغاز|حزوره|riddle)/)) { const [q, a] = pick(RIDDLES); riddles.set(ch, { a: norm(a), at: Date.now() }); return `🧩 ${q}\n> اكتب جوابك، أو «استسلم»`; }
  if (has(/(حكمه|نصيحه|قول شي حلو|اقتباس)/)) return R(WISDOM);
  if (has(/(مدح|امدحني|قول شي عني)/)) return R(COMPLIMENTS);
  if (has(/(العب|نلعب|لعبه|play)/)) return R(['يلا! لعبة جماعية تبدأ الآن {e} [game:chairs]', 'تحدي أسرع واحد يكتب! [game:fastest]', 'اختر: «سلوت 500» · «كنز 300» · «سباق 200» · «خمن الرقم» · أو «العاب» للقائمة كاملة {e}']);

  // 7) أسئلة عن الأوامر — يشرح ويشغّل
